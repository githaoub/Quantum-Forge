"""Upload the three custom currency PNGs and rewrite `AssetManifest.CurrencyArt`.

These are not generated by `generate_icons.py`; they come from the art pipeline
with a chroma background removed, so they get their own key table and their own
cache file. The uploader itself is shared with `upload_assets.py` so the
multipart body, retry policy and operation polling cannot drift.

Usage:
    python scripts/upload_currency.py --creator user:1416845247
    python scripts/upload_currency.py --creator user:1416845247 --dry-run
    python scripts/upload_currency.py --manifest-only

Requires `ROBLOX_API_KEY` (or `ROBLOX_OPEN_CLOUD_KEY`) with `asset:write`.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import upload_assets as ua  # noqa: E402

CURRENCY_DIR = ua.GENERATED_DIR / "currency"
CACHE_PATH = CURRENCY_DIR / "uploaded.json"

# Manifest key -> source file. The keys are what `AssetManifest.currencyArt`
# reads; the HUD maps star/crystal/core to sm/as/qc.
SOURCES: dict[str, str] = {
    "sm": "star_matter.png",
    "as": "aether.png",
    "qc": "cores.png",
}

BLOCK_RE = re.compile(r"(AssetManifest\.CurrencyArt = \{)(.*?)(\n\})", re.S)


def render_block(ids: dict[str, str]) -> str:
    lines = [f'\t{key} = "{ids.get(key, "")}",' for key in SOURCES]
    return "\n" + "\n".join(lines)


def write_manifest(ids: dict[str, str]) -> None:
    if not ua.MANIFEST_PATH.is_file():
        sys.exit(f"manifest not found: {ua.MANIFEST_PATH}")
    text = ua.MANIFEST_PATH.read_text(encoding="utf-8")
    match = BLOCK_RE.search(text)
    if match is None:
        sys.exit(
            "could not find the `AssetManifest.CurrencyArt = { ... }` table in "
            f"{ua.MANIFEST_PATH}"
        )
    text = text[: match.start(2)] + render_block(ids) + text[match.end(2) :]
    ua.MANIFEST_PATH.write_text(text, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--creator",
        default="user:1416845247",
        help="user:123456 or group:123456 (default: the project owner)",
    )
    parser.add_argument("--force", action="store_true", help="re-upload even if the hash matches")
    parser.add_argument("--dry-run", action="store_true", help="print the plan, upload nothing")
    parser.add_argument(
        "--manifest-only",
        action="store_true",
        help="rebuild AssetManifest.CurrencyArt from the local cache",
    )
    args = parser.parse_args()

    cache = ua.load_json(CACHE_PATH)
    if not isinstance(cache, dict):
        cache = {}

    if args.manifest_only:
        ids = {key: str(cache.get(key, {}).get("assetId", "")) for key in SOURCES}
        write_manifest(ids)
        live = sum(1 for value in ids.values() if value)
        print(f"CurrencyArt rebuilt: {live}/{len(SOURCES)} keys resolved")
        return 0

    api_key = ua.api_key_from_env()
    if not args.dry_run and not api_key:
        sys.exit(
            "ROBLOX_API_KEY is not set. Create a key with the asset:write scope at "
            "https://create.roblox.com/dashboard/credentials then:\n"
            '  setx ROBLOX_API_KEY "your-key-here"'
        )

    if ua.requests is None and not args.dry_run:
        sys.exit("requests is required to upload. Run: pip install -r requirements.txt")

    todo: list[tuple[str, Path, str]] = []
    for key, filename in SOURCES.items():
        path = CURRENCY_DIR / filename
        try:
            ua.validate_png(path)
        except (FileNotFoundError, ValueError) as exc:
            sys.exit(f"{key}: {exc}")
        digest = ua.file_hash(path)
        cached = cache.get(key, {})
        if not args.force and cached.get("hash") == digest and cached.get("assetId"):
            continue
        todo.append((key, path, digest))

    print(f"{len(SOURCES)} currency assets, {len(todo)} to upload")
    for key, path, _ in todo:
        print(f"  {key:<3} {path.name:<18} {path.stat().st_size / 1024:.0f} KiB")

    if args.dry_run:
        return 0

    if not todo:
        ids = {key: str(cache.get(key, {}).get("assetId", "")) for key in SOURCES}
        write_manifest(ids)
        return 0

    creator = ua.parse_creator(args.creator)
    session = ua.requests.Session()
    failures: list[tuple[str, str]] = []

    for key, path, digest in todo:
        print(f"[{key}] {path.name} -> upload")
        try:
            asset_id = ua.upload_asset(
                session,
                api_key,
                path,
                display_name=f"Quantum Forge Currency {key.upper()}",
                creator=creator,
                asset_type="Image",
                content_type="image/png",
                description="Quantum Forge - custom currency art",
            )
        except ua.UploadError as exc:
            print(f"    FAILED: {exc}")
            failures.append((key, str(exc)))
            continue
        cache[key] = {"hash": digest, "assetId": asset_id, "file": path.name}
        ua.save_json(CACHE_PATH, cache)
        print(f"    uploaded as {asset_id}")

    ids = {key: str(cache.get(key, {}).get("assetId", "")) for key in SOURCES}
    write_manifest(ids)
    live = sum(1 for value in ids.values() if value)
    print(f"CurrencyArt: {live}/{len(SOURCES)} keys resolved")

    if failures:
        for key, reason in failures:
            print(f"  {key}: {reason}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
